export type MediaFolder = 'blogs' | 'portfolio' | 'services' | 'site' | 'team';

const ALLOWED_IMAGE_TYPES = [
  'image/jpeg',
  'image/jpg',
  'image/png',
  'image/webp',
  'image/avif',
  'image/svg+xml',
];

const MAX_UPLOAD_BYTES = 5 * 1024 * 1024;

export async function uploadMediaFile(
  file: File,
  folder: MediaFolder,
  onProgress?: (pct: number) => void,
): Promise<string> {
  if (!ALLOWED_IMAGE_TYPES.includes(file.type)) {
    throw new Error('Please upload a JPG, PNG, WebP, AVIF, or SVG image.');
  }
  if (file.size > MAX_UPLOAD_BYTES) {
    throw new Error('Image size must be 5 MB or less.');
  }

  const safeName = file.name.replace(/[^a-zA-Z0-9._-]/g, '_').toLowerCase();
  const objectPath = `media/${folder}/${Date.now()}_${safeName}`;
  const storageRef = ref(storage, objectPath);

  return new Promise((resolve, reject) => {
    const task = uploadBytesResumable(storageRef, file, {
      contentType: file.type,
    });

    task.on(
      'state_changed',
      (snapshot) => {
        if (onProgress && snapshot.totalBytes > 0) {
          onProgress(Math.round((snapshot.bytesTransferred / snapshot.totalBytes) * 100));
        }
      },
      (error) => {
        reject(
          new Error(
            error.message.includes('storage/unauthorized')
              ? 'Storage upload unauthorized. Verify you are signed in as admin and Firebase Storage rules are deployed.'
              : `Upload failed: ${error.message}. Ensure Firebase Storage is enabled in your Firebase Console, or paste a direct image URL.`,
          ),
        );
      },
      async () => {
        try {
          const url = await getDownloadURL(task.snapshot.ref);
          resolve(url);
        } catch (err) {
          reject(err);
        }
      },
    );
  });
}
